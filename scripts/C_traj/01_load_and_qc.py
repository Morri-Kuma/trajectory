# Seurat v3 HVG selection: variance-stabilizing transformation (VST)
# Standardized variance: var / expected_var given mean (loess fit in Seurat)
# Simplified approach: use the log-variance / log-mean relationship
# Rank genes by their residual variance after regressing out the mean-variance trend

# For a robust approach without loess: bin genes by mean, compute expected var per bin
valid = gene_passes & (gene_mean > 0)
log_mean = np.full(N_GENES_REF, np.nan)
log_var  = np.full(N_GENES_REF, np.nan)
log_mean[valid] = np.log10(gene_mean[valid] + 1e-10)
log_var[valid]  = np.log10(gene_var[valid] + 1e-10)

# Bin by mean expression, compute expected variance per bin
n_bins = 20
valid_idx = np.where(valid)[0]
lm = log_mean[valid]
lv = log_var[valid]
bin_edges = np.percentile(lm, np.linspace(0, 100, n_bins + 1))
bin_edges[0] -= 1e-10
bin_edges[-1] += 1e-10
bin_assignment = np.digitize(lm, bin_edges) - 1
bin_assignment = np.clip(bin_assignment, 0, n_bins - 1)

expected_var = np.zeros(len(lm))
for b in range(n_bins):
    mask = bin_assignment == b
    if mask.sum() > 0:
        expected_var[mask] = np.median(lv[mask])

# Residual = observed variance - expected variance (higher = more variable)
